export function categoryLabel(id: LeadCategory) {
  return categoryFilters.find((item) => item.id === id)?.label ?? id;
}

export function stageLabel(id: LeadStage) {
  return stages.find((item) => item.id === id)?.label ?? id;
}

export function neighborStage(stage: LeadStage, direction: -1 | 1): LeadStage | null {
  const index = stages.findIndex((item) => item.id === stage);
  return stages[index + direction]?.id ?? null;
}
