export function validateIcons(): void {
  for (const type of pixelIconTypes) {
    const rows = pixelIcons[type];
    if (rows.length !== 16 || rows.some((row) => row.length !== 16)) {
      throw new Error(`Pixel icon ${type} must be 16 by 16`);
    }
  }
}
